// Extracts the procedural generator from LingDong-'s shan-shui-inf index.html
// and turns it into gen-core.js: a pure function with no DOM access, safe to run
// inside a Web Worker. Every patch is an exact-match replacement that must apply
// exactly once, so an upstream change fails the build loudly instead of silently.
//
// usage: node tools/build.mjs [path/to/shan-shui-inf/index.html]
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const src = process.argv[2] ?? join(here, "..", "..", "shan-shui-inf-src", "index.html");
const html = readFileSync(src, "utf8").replace(/\r\n/g, "\n");

// 1. Keep only the generator: everything before the mouse/SVG/UI glue.
const cut = html.indexOf('document.addEventListener("mousemove"');
if (cut < 0) throw new Error("cut marker not found");
let code = html.slice(0, cut);

// 2. Drop <script> tags (the blocks are concatenated in document order).
code = code.replace(/<script[^>]*>/g, "").replace(/<\/script>/g, "");

function patch(from, to) {
  const n = code.split(from).length - 1;
  if (n !== 1) throw new Error(`patch expected 1 match, got ${n}: ${from.slice(0, 60)}`);
  code = code.replace(from, () => to);
}

// window.btoa does not exist in workers; btoa does.
patch("window.btoa(JSON.stringify(x))", "btoa(JSON.stringify(x))");

// URL-driven seed -> injected seed.
patch(
  /function parseArgs\(key2f\)[\s\S]*?console\.log\(Prng\.seed\);/.exec(code)[0],
  "Math.seed(SEED);",
);

// poly(): emit a compact token instead of an SVG <polyline>. String concatenation
// order is preserved, so paint order is identical to the original SVG.
// Token: \x01 fill \x02 stroke \x02 width \x02 x,y,x,y,... \x03
patch(
  /var canv = "<polyline points='";[\s\S]*?"'\/>";\n    return canv;/.exec(code)[0],
  `var n = plist.length, pts = new Array(n * 2);
    for (var i = 0; i < n; i++) {
      pts[2 * i] = (plist[i][0] + xof).toFixed(1);
      pts[2 * i + 1] = (plist[i][1] + yof).toFixed(1);
    }
    return "\\x01" + fil + "\\x02" + str + "\\x02" + wid + "\\x02" + pts.join(",") + "\\x03";`,
);

// Signboard <text> -> token \x04 size \x02 x \x02 y \x02 deg \x02 text \x03
patch(
  /"<text font-size='" \+[\s\S]*?"<\/text>";/.exec(code)[0],
  `"\\x04" + hei * 0.6 + "\\x02" + (mp[0] + xoff) + "\\x02" + (mp[1] + yoff) +
          "\\x02" + adeg + "\\x02" + pla[1] + "\\x03";`,
);

// The generator logs on every placement; console I/O is the slowest thing it does.
const out = `// GENERATED by tools/build.mjs from shan-shui-inf (MIT, (c) 2018 Lingdong Huang).
// Do not edit by hand; edit the patches in tools/build.mjs instead.
function SHANSHUI_CORE(SEED) {
  var console = { log: function () {} };
  var MEM;
${code}
  return { MEM: MEM, chunkloader: chunkloader, Noise: Noise };
}
`;
writeFileSync(join(here, "..", "gen-core.js"), out);
console.log(`gen-core.js written (${(out.length / 1024).toFixed(0)} KiB)`);
